#!/bin/bash
# Prepare an ElmLean native app for Xcode: build it with Lake, gather the C that Lean generated for the
# app and for the ElmLean framework, write the initializer the C shim calls, and retarget Lean's
# runtime and standard library (macOS arm64 static libraries) to the iOS simulator.
#
#   ios_lean_sources.sh <app package dir> <root module> <out dir> [iossim|ios]
#
# Out: <out>/lean-c/*.c (one per Lean module, flattened), <out>/lean-c/elm_app_initialize.c,
#      <out>/native-shell/*.swift (the shell, printed by `lake exe elmshell`: build output, never a source),
#      <out>/lib/{libLean,libStd,libInit,libleanrt,libuv,libgmp}.a
# The retargeting rewrites each object's LC_BUILD_VERSION (platform 7 = iOS simulator, 2 = iOS); Lean
# does not support this, and only the simulator has been verified.
set -euo pipefail
APP="$(cd "$1" && pwd)"; ROOT="$2"; OUT="$3"; PLATFORM="${4:-iossim}"
HERE="$(cd "$(dirname "$0")" && pwd)"
FW_LEAN="$(cd "$HERE/../../lean" && pwd)"
TOOLCHAIN="$(cd "$APP" && elan which lean | xargs dirname | xargs dirname)"
mkdir -p "$OUT/lean-c" "$OUT/lib" "$OUT/native-shell"
OUT_ABS="$(cd "$OUT" && pwd)"
(cd "$APP" && lake build >/dev/null)
# the shell's Swift, printed from framework/lean/ElmShell (its checks against the protocol run first)
(cd "$APP" && lake exe elmshell "$OUT_ABS/native-shell")
rm -f "$OUT/lean-c/"*.c
# the C of every module in the root's import closure (app and ElmLean only; Init/Std/Lean are the libraries)
# every package the app depends on by path (from its lake-manifest.json), plus ElmLean itself
PKGS=$(/usr/bin/python3 -c '
import json, os, sys
app = sys.argv[1]
m = json.load(open(os.path.join(app, "lake-manifest.json")))
for p in m.get("packages", []):
    d = p.get("dir") or p.get("path")
    if d and p.get("type", "path") == "path":
        print(os.path.realpath(os.path.join(app, d)))
' "$APP")
IFS=$'\n' read -r -d '' -a PKG_DIRS <<< "$PKGS" || true
/usr/bin/python3 "$HERE/import_closure.py" "$ROOT" "$APP" "$FW_LEAN" "${PKG_DIRS[@]}" | while IFS=$'\t' read -r pkgdir mod; do
  f="$pkgdir/.lake/build/ir/$(echo "$mod" | tr '.' '/').c"
  [ -f "$f" ] || { echo "missing C for $mod ($f)" >&2; exit 1; }
  grep -q '^int main(' "$f" && continue
  cp "$f" "$OUT/lean-c/$(echo "$mod" | tr '.' '_').c"
done
pkg=$(grep -m1 '^name' "$APP/lakefile.toml" | sed 's/.*= *"\(.*\)"/\1/')
sym="initialize_${pkg}_$(echo "$ROOT" | tr '.' '_')"
cat > "$OUT/lean-c/elm_app_initialize.c" <<C
// Generated by ios_lean_sources.sh: the app's root module initializer, called by elmlean_boot().
#include <lean/lean.h>
lean_object *$sym(uint8_t builtin);
lean_object *elm_app_initialize(void) { return $sym(1); }
C
case "$PLATFORM" in iossim) plat=7 ;; ios) plat=2 ;; *) echo "platform: iossim or ios" >&2; exit 2 ;; esac
for l in lean/libLean.a lean/libStd.a lean/libInit.a lean/libleanrt.a libuv.a libgmp.a; do
  out="$OUT/lib/$(basename "$l")"
  [ "$out" -nt "$TOOLCHAIN/lib/$l" ] || /usr/bin/python3 "$HERE/retarget_ar.py" "$plat" 17.0 "$TOOLCHAIN/lib/$l" "$out" >/dev/null
done
echo "$OUT/lean-c: $(ls "$OUT/lean-c" | wc -l | tr -d ' ') C files; $OUT/native-shell: $(ls "$OUT/native-shell" | wc -l | tr -d ' ') Swift files; $OUT/lib: retargeted to $PLATFORM; toolchain $TOOLCHAIN"
